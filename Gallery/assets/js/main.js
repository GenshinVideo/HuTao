const container = document.getElementById("gallery-container");

galleries.forEach(gallery => {
  const title = document.createElement("p");
  title.style.marginBottom = "0px";

  const bold = document.createElement("b");
  bold.textContent = gallery.title;
  title.appendChild(bold);
  container.appendChild(title);

  const section = document.createElement("div");
  section.className = "gallery";

  gallery.images.forEach(item => {
    const file = typeof item === "string" ? item : item.file;
    const path = gallery.date + "/" + file;

    const link = document.createElement("a");
    link.href = IMAGE_BASE + path;

    if (typeof item !== "string" && item.source) {
      link.setAttribute(
        "data-sub-html",
        `<p>Source: <a href="${item.source.url}" target="_blank" rel="noopener noreferrer">${item.source.name}</a></p>`
      );
    }

    const img = document.createElement("img");
    img.className = "lazy";
    img.setAttribute(
      "data-src",
      IMAGE_BASE + gallery.date + "/thumbnail/" +
      file.replace(/\.(png|jpe?g)$/i, ".webp")
    );

    link.appendChild(img);
    section.appendChild(link);
  });

  container.appendChild(section);
});

